# ==============================================================================
# Script Otomatis Sinkronisasi Folder Media & Data JSON
# Memindai semua gambar & video di dalam folder "media/" lalu memperbarui
# data/media.json serta data/fallback-data.js (agar HTML bisa dibuka langsung
# tanpa kendala CORS browser).
# ==============================================================================

$ErrorActionPreference = "Stop"
$RootDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$MediaDir = Join-Path $RootDir "media"
$DataDir = Join-Path $RootDir "data"

if (-not (Test-Path $MediaDir)) {
    New-Item -ItemType Directory -Path $MediaDir | Out-Null
}
if (-not (Test-Path $DataDir)) {
    New-Item -ItemType Directory -Path $DataDir | Out-Null
}

$ImageExtensions = @(".jpg", ".jpeg", ".png", ".webp", ".gif", ".svg", ".bmp")
$VideoExtensions = @(".mp4", ".webm", ".ogg", ".mov", ".m4v")

$MediaItems = @()
$Files = Get-ChildItem -Path $MediaDir -File | Sort-Object Name

foreach ($File in $Files) {
    $Ext = $File.Extension.ToLower()
    $BaseName = [System.IO.Path]::GetFileNameWithoutExtension($File.Name) -replace "[-_]", " "
    if ($ImageExtensions -contains $Ext) {
        $MediaItems += [PSCustomObject]@{
            file     = "media/$($File.Name)"
            type     = "image"
            title_en = $BaseName
            title_bs = $BaseName
        }
    } elseif ($VideoExtensions -contains $Ext) {
        $MediaItems += [PSCustomObject]@{
            file     = "media/$($File.Name)"
            type     = "video"
            title_en = $BaseName
            title_bs = $BaseName
        }
    }
}

$MediaJsonObj = [PSCustomObject]@{
    image_duration_seconds = 8
    last_synced            = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
    items                  = $MediaItems
}

$MediaJsonPath = Join-Path $DataDir "media.json"
$MediaJsonString = $MediaJsonObj | ConvertTo-Json -Depth 5
[System.IO.File]::WriteAllText($MediaJsonPath, $MediaJsonString, [System.Text.Encoding]::UTF8)

$TimetablePath = Join-Path $DataDir "timetable.json"
$BellSchedulePath = Join-Path $DataDir "bell_schedule.json"

$TimetableRaw = if (Test-Path $TimetablePath) { [System.IO.File]::ReadAllText($TimetablePath, [System.Text.Encoding]::UTF8) } else { "{}" }
$BellScheduleRaw = if (Test-Path $BellSchedulePath) { [System.IO.File]::ReadAllText($BellSchedulePath, [System.Text.Encoding]::UTF8) } else { "{}" }

$FallbackJsPath = Join-Path $DataDir "fallback-data.js"
$FallbackJsContent = @"
// Auto-generated by sync-media.bat - Do not edit manually
// Allows index.html to work seamlessly both via HTTP server and direct file:// double-click
window.FALLBACK_TIMETABLE_DATA = $TimetableRaw;
window.FALLBACK_BELL_DATA = $BellScheduleRaw;
window.FALLBACK_MEDIA_DATA = $MediaJsonString;
"@

[System.IO.File]::WriteAllText($FallbackJsPath, $FallbackJsContent, [System.Text.Encoding]::UTF8)
Write-Host "[OK] Berhasil menyinkronkan $($MediaItems.Count) file media dari folder media/ ke data/media.json & data/fallback-data.js" -ForegroundColor Green
